package be.intecbrussel.les3;

/** Les 3: de eenvoudigste if — het blok wordt alleen uitgevoerd als de voorwaarde waar is. */
public class IfCondition {
    public static void main(String[] args) {
        int num = 10;

        if (num < 100) {
            System.out.println("The value is smaller than 100");
        }
    }
}
