package be.intecbrussel.les2;

/** Oefening: oppervlakte berekenen met float-variabelen (f-suffix verplicht). */
public class Oefening1 {
    public static void main(String[] args) {
        float lang = 12.5f; // zonder f-suffix is een kommagetal standaard een double
        float breed = 7.8f;

        System.out.println(lang * breed);
    }
}
